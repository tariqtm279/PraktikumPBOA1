    private void listIdValueChanged() {
        int index = listId.getSelectedIndex();
        if (index != -1) {
            // Samakan sorotan listNama dengan listId agar sinkron
            listNama.setSelectedIndex(index);
            
            String selectedId = listId.getSelectedValue();
            String selectedNama = listNama.getModel().getElementAt(index);
            
            // Isi textfield edit secara otomatis
            txtIdEdit.setText(selectedId);
            txtNamaEdit.setText(selectedNama);
            
            // Isi textfield hapus secara otomatis
            txtIdHapus.setText(selectedId);
            jTextField5.setText(selectedNama); 
        }
    }

    private void listNamaValueChanged() {
        int index = listNama.getSelectedIndex();
        if (index != -1) {
            // Samakan sorotan listId dengan listNama agar sinkron
            listId.setSelectedIndex(index);
            
            String selectedId = listId.getModel().getElementAt(index);
            String selectedNama = listNama.getSelectedValue();
            
            // Isi textfield edit secara otomatis
            txtIdEdit.setText(selectedId);
            txtNamaEdit.setText(selectedNama);
            
            // Isi textfield hapus secara otomatis
            txtIdHapus.setText(selectedId);
            jTextField5.setText(selectedNama);
        }
    }
    
