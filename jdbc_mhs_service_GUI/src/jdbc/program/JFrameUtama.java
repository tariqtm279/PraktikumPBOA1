    private void jButtonTambahkanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonTambahkanActionPerformed
        // TODO add your handling code here:
        String inputNama = txtInputNama.getText().trim();
        if (!inputNama.isEmpty()) {
            jdbc.model.Mahasiswa mhsAdd = new jdbc.model.Mahasiswa(inputNama);
            service.add(mhsAdd); // Kirim data ke DB
        
            txtInputNama.setText(""); // Kosongkan field input
            displayToGUI();           // Refresh tampilan layar
        }
    }//GEN-LAST:event_jButtonTambahkanActionPerformed

    private void jButtonEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEditActionPerformed
        // TODO add your handling code here:
        String strId = txtIdEdit.getText().trim();
        String namaBaru = txtNamaEdit.getText().trim();
    
        if (!strId.isEmpty() && !namaBaru.isEmpty()) {
            int id = Integer.parseInt(strId);
            jdbc.model.Mahasiswa mhsUpdate = new jdbc.model.Mahasiswa(id, namaBaru);
            service.update(mhsUpdate); // Update data di DB
        
            txtNamaEdit.setText("");   // Kosongkan inputan
            displayToGUI();          // Refresh tampilan layar
         }
    }//GEN-LAST:event_jButtonEditActionPerformed

    private void jButtonHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonHapusActionPerformed
        // TODO add your handling code here:
        String strId = txtIdHapus.getText().trim();
        if (!strId.isEmpty()) {
            int id = Integer.parseInt(strId);
            service.delete(id); // Hapus data di DB
        
            txtIdHapus.setText(""); 
            jTextField5.setText(""); // Mengosongkan field nama pada baris hapus
        
            // kosongkan juga field edit agar tidak menyisa data lama
            txtIdEdit.setText("");
            txtNamaEdit.setText("");
        
        displayToGUI();         // Refresh tampilan layar
        }
    }//GEN-LAST:event_jButtonHapusActionPerformed

